import { normalize } from '../../lib/arabic'
import type { Task } from '../../types'

/**
 * يفهم المقصود من طلب الطالب. القواعد مرتبة: الأكثر تحديداً أولاً،
 * فـ«اشرح لي الفرق بين…» مقارنة، و«اشرح هذه المعادلة خطوة بخطوة» شرح خطوات.
 */
const RULES: [Task, RegExp][] = [
  ['teach', /(^|\s)(علمني|درسني|علمنى)(\s|$)|علمني (هذا |ال)?(الدرس|درس)|خطوه بخطوه.*(الدرس|درس)|(الدرس|درس).*خطوه بخطوه/],
  ['check', /(اختبرني|اختبرنى|اسالني|امتحني|امتحنى|اختبر فهمي|سوال (للتدريب|تدريبي)|سوالا (للتدريب|تدريبيا)|سوال اخر|سوالا اخر)/],
  ['compare', /(الفرق بين|الفروق بين|قارن|مقارنه بين|اوجه الشبه|اوجه الاختلاف|ما الفرق)/],
  ['summary', /(لخص|ملخص|تلخيص|الخلاصه)/],
  ['points', /(اهم (الاشياء|النقاط|ما|المعلومات)|(يجب|لازم|علي) (ان )?احفظ|نقاط الحفظ|ماذا احفظ|ما الذي احفظه)/],
  ['mistakes', /(الاخطاء|اخطاء|اخطئ|اقع فيها|الاخطا الشايعه|اغلاط)/],
  ['steps', /(خطوه بخطوه|حل (هذه |هذا )?(المساله|المسائل|التمرين)|كيف احل|اشرح (لي )?(هذه |هذا )?(المعادله|القانون|المساله|الحل))/],
  ['examples', /(مثال|امثله|مثالا)/],
  ['terms', /(المصطلحات|معنى المصطلح|وضح (لي )?المصطلح)/],
  ['explain', /((اشرح|فهمني|وضح)( لي)? (هذا |ال)?(الدرس|درس|الفصل|الوحده|الباب|الموضوع))|من البدايه|لم افهم (هذا )?(الدرس|درس)|ما فهمت (الدرس|درس)|ما فهمتش/],
]

/** توحيد أوسع لمطابقة الأوامر فقط */
export const norm = (s: string) => normalize(s).replace(/ؤ/g, 'و').replace(/ئ/g, 'ي').replace(/[ًٌٍَُِّْ]/g, '')

export function classify(text: string): Task {
  const t = norm(text)
  return RULES.find(([, re]) => re.test(t))?.[0] ?? 'answer'
}

/** المهام التي تقرأ الدرس كله لا نتائج البحث */
export const LESSON_TASKS: Task[] = ['explain', 'teach', 'summary', 'points', 'mistakes', 'terms']

/** كلمات الطلب نفسه: ما يبقى بعدها هو الموضوع، مثل «الحرارة» في «اشرح لي درس الحرارة» */
const COMMAND = new Set(
  'اشرح اشرحي فهمني وضح علمني درسني لخص ملخص اختبرني اسالني امتحني اعطني اريد ممكن من فضلك لي لو سمحت هذا هذه الدرس درس الفصل فصل الوحده وحده الباب باب الموضوع موضوع البدايه خطوه بخطوه لم ما افهم فهمت اهم النقاط الاشياء التي الذي يجب ان احفظ الاخطاء اخطاء اقع فيها في عن امثله مثال على المصطلحات بالتفصيل ببساطه مبسط شرحا كاملا كامل و يا'.split(' '),
)
export function topicOf(text: string) {
  return norm(text).split(/[^\p{L}\p{N}]+/u).filter((w) => w && !COMMAND.has(w)).join(' ')
}

/** إجابة عن سؤال فهم، أم طلب جديد؟ */
export function looksLikeRequest(text: string) {
  const t = norm(text)
  return classify(text) !== 'answer' || /[؟?]\s*$/.test(text) || /^(ما|ماذا|لماذا|كيف|هل|متى|اين|من هو|من هي|لم افهم|ما فهمت|وضح|اشرح|اعد|تلميح|ساعدني)(\s|$)/.test(t)
}
