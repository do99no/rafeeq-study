import { chat } from '../ai/manager'
import { load, save } from '../storage/local'

/**
 * الشرح الصوتي منفصل عن المكتوب: المكتوب يبقى فصيحاً كما هو، والمسموع «نص منطوق» بالعربية البيضاء السهلة
 * مع لمسة مصرية خفيفة، كمدرس هادئ يشرح لطالب. يُكتب النص المنطوق مرة واحدة لكل رد (طلب واحد) ويُحفظ على الجهاز.
 * المصطلحات والقوانين والأرقام لا تتغير، ونصوص الكتاب المقتبسة والآيات والتعريفات تُقرأ بالفصحى كما هي.
 * إن تعذّرت الخدمة: تُقرأ الرسالة كما كُتبت (بالفصحى)، فلا يتوقف الصوت.
 */
export const SPOKEN_SYSTEM = `أنت مدرس هادئ يشرح لطالب سوداني في الصف الثالث الثانوي بصوته. ستُعطى نصاً مكتوباً بالفصحى، وتعيد كتابته «نصاً يُقال بصوت عالٍ».

اللغة:
- عربية بيضاء سهلة مفهومة لكل العرب، مع لمسة مصرية خفيفة وطبيعية في الربط والتشجيع فقط، مثل: «خلينا نفهم»، «بص للفكرة دي»، «تعال نطبق مع بعض»، «يعني إيه؟»، «خد بالك». استعمل تعبيراً أو اثنين في الفقرة على الأكثر، لا في كل جملة.
- لا عامية مصرية ثقيلة، ولا فصحى رسمية جامدة.

الدقة (إلزامي):
- لا تغيّر أي مصطلح علمي أو رياضي أو نحوي، ولا اسم قانون، ولا رقم، ولا وحدة، ولا نتيجة. اذكر المصطلح كما هو ثم وضّحه بكلمات بسيطة إن لزم.
- لا تضف معلومة ليست في النص، ولا تحذف خطوة من الحل.
- ما بين علامتي تنصيص «» أو المسبوق بـ > (اقتباس من الكتاب)، والآيات القرآنية والأحاديث، والتعريفات الحرفية: انقلها بالفصحى كما هي حرفياً، وقدّم لها بعبارة مثل «الكتاب بيقول:».

النطق:
- اكتب العمليات والرموز كلاماً منطوقاً: «س تربيع زائد ٣س يساوي ١٠»، «ف على ز»، «جذر ٢». اترك الأرقام أرقاماً كما هي.
- لا رموز تنسيق (#، *، |، أرقام استشهاد [١])، ولا جداول: حوّل الجدول إلى جمل.
- جمل قصيرة، وكل فكرة في سطر، ووقفات طبيعية.
- اكتب النص المنطوق فقط، دون مقدمة أو تعليق.`

const key = (id: string) => `spoken:${id}`
export const cachedSpoken = (id: string) => load<string>(key(id))

export async function spokenScript(id: string, text: string, signal: AbortSignal): Promise<string | null> {
  const have = cachedSpoken(id)
  if (have) return have
  let out = ''
  try {
    for await (const ev of chat([{ role: 'system', content: SPOKEN_SYSTEM }, { role: 'user', content: `النص المكتوب:\n\n${text.slice(0, 12000)}` }], { maxTokens: 6000, signal })) {
      if (ev.type === 'reset') out = ''
      else if (ev.type === 'text') out += ev.text
    }
  } catch {
    return null
  }
  out = out.trim()
  // حماية الدقة: كل رقم في المكتوب يجب أن يبقى في المنطوق (بالأرقام أو بالكلمات)، وإلا يُقرأ المكتوب كما هو
  if (!out || !numbersKept(text, out)) return null
  save(key(id), out)
  return out
}

const AR_NUM: Record<string, string[]> = {
  '0': ['صفر'], '1': ['واحد', 'واحدة'], '2': ['اتنين', 'اثنين', 'اثنان', 'اتنان'], '3': ['تلاتة', 'ثلاثة', 'تلات', 'ثلاث'], '4': ['أربعة', 'اربعة', 'أربع'], '5': ['خمسة', 'خمس'],
  '6': ['ستة', 'ست'], '7': ['سبعة', 'سبع'], '8': ['تمانية', 'ثمانية', 'تمن', 'ثمان'], '9': ['تسعة', 'تسع'], '10': ['عشرة', 'عشر'],
}
/** الأرقام المهمة (حتى ٢٠ رقماً) في المكتوب موجودة في المنطوق بصورة ما */
export function numbersKept(written: string, spoken: string) {
  const lat = (s: string) => s.replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x660))
  const nums = [...new Set(lat(written.replace(/\[\d+\]/g, '')).match(/\d+(?:[.,٫]\d+)?/g) ?? [])].slice(0, 20)
  const sp = lat(spoken)
  return nums.every((n) => sp.includes(n) || (AR_NUM[n] ?? []).some((w) => sp.includes(w)) || n.length > 3)
}
